/** Localizes common COCO class labels for display while leaving the source label untouched. */
export function getYoloClassLabel(label: string, language: string): string {
  const translations = COCO_CLASS_LABELS[label.trim().toLowerCase()];
  if (!translations) return label;
  return language.toLowerCase().startsWith("pt") ? translations["pt-BR"] : translations.en;
}
